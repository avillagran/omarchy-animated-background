#!/usr/bin/env python3
"""Convert an nfd/sota shapes JSON file into a RETRO Lua scene.

The input format is the one consumed by shapes/sota.js:
  {"indices": [...], "data": [...]}
It converts dX polygon commands and e6/e7/e8/f2 tween commands to pre-baked
per-frame Lua polygon arrays. Original source assets stay outside this repo.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

PLANE_COLORS = {
    0: "#ffffff",
    1: "#ff3bd4",
    2: "#52d7ff",
    3: "#aaff55",
}


def ints(values):
    return [int(v) for v in values]


def read_polygon(data: list[int], command_pos: int):
    command = data[command_pos]
    if command & 0xF0 != 0xD0:
        raise ValueError(f"expected polygon command at data[{command_pos}], got {command:#x}")
    count = data[command_pos + 1]
    start = command_pos + 2
    end = start + count * 2
    if end > len(data):
        raise ValueError(f"polygon at {command_pos} exceeds data array")
    # SOTA stores vertices as (y, x); the Lua renderer uses (x, y).
    points = []
    for i in range(start, end, 2):
        y, x = data[i], data[i + 1]
        points.extend((x, y))
    return command & 0x0F, points, end


def tween_polygon(data: list[int], current: int):
    from_pos = current - ((data[current] << 8) | data[current + 1])
    current += 2
    to_pos = current + ((data[current] << 8) | data[current + 1])
    current += 2
    tween_t, tween_count = data[current], data[current + 1]
    plane_from, from_points, _ = read_polygon(data, from_pos)
    plane_to, to_points, _ = read_polygon(data, to_pos)
    count = max(len(from_points), len(to_points))
    if count % 2:
        raise ValueError("polygon coordinate count is not even")
    amount = tween_t / max(1, tween_count)
    points = []
    for i in range(0, count, 2):
        fi = min(len(from_points) - 2, int(i * len(from_points) / count))
        ti = min(len(to_points) - 2, int(i * len(to_points) / count))
        y = int(from_points[fi] + amount * (from_points[fi] - from_points[fi] + to_points[ti] - from_points[fi]))
        x = int(from_points[fi + 1] + amount * (to_points[ti + 1] - from_points[fi + 1]))
        points.extend((x, y))
    return plane_from if plane_from == plane_to else 0, points


def frame_polygons(data: list[int], start: int):
    if start < 0 or start >= len(data):
        raise ValueError(f"frame index {start} outside data array")
    count = data[start]
    cursor = start + 1
    result = []
    for _ in range(count):
        command = data[cursor]
        cursor += 1
        if command & 0xF0 == 0xD0:
            plane, points, cursor = read_polygon(data, cursor - 1)
        elif command in (0xE6, 0xE7, 0xE8, 0xF2):
            plane, points = tween_polygon(data, cursor)
            cursor += 6
        else:
            raise ValueError(f"unsupported SOTA draw command {command:#x} at {cursor - 1}")
        result.append((plane, points))
    return result


def lua_number(value):
    return str(int(value))


def convert(source: Path, target: Path, width: int, height: int):
    doc = json.loads(source.read_text())
    indices = ints(doc["indices"])
    data = ints(doc["data"])
    frames = [frame_polygons(data, idx) for idx in indices]
    lines = [
        "-- Generated by sota-json-to-lua.py from an nfd/sota shapes JSON.",
        "-- Geometry is converted from SOTA (y,x) vertices to Lua (x,y).",
        f"local SOURCE_W, SOURCE_H = 256, 205",
        f"local VIEW_W, VIEW_H = {width}, {height}",
        "local frames = {",
    ]
    for frame in frames:
        lines.append("  {")
        for plane, points in frame:
            coords = ",".join(lua_number(v) for v in points)
            lines.append(f"    {{plane={plane}, points={{{coords}}}}},")
        lines.append("  },")
    lines += [
        "}",
        "local colors = {",
    ]
    for plane in range(4):
        lines.append(f"  [{plane}] = \"{PLANE_COLORS[plane]}\",")
    lines += [
        "}",
        "return function(frame, a)",
        "  local c = {a.clear(\"#000000\")}",
        "  local source = frames[(frame % #frames) + 1]",
        "  for _, polygon in ipairs(source) do",
        "    local p = polygon.points",
        "    local scaled = {}",
        "    for i=1,#p,2 do",
        "      scaled[#scaled+1] = p[i] * VIEW_W / SOURCE_W",
        "      scaled[#scaled+1] = p[i+1] * VIEW_H / SOURCE_H",
        "    end",
        "    scaled[#scaled+1] = scaled[1]; scaled[#scaled+1] = scaled[2]",
        "    c[#c+1] = a.poly(scaled, colors[polygon.plane] or \"#ffffff\", true)",
        "  end",
        "  if a.beat then c[#c+1] = a.rect(0, 0, VIEW_W, VIEW_H, \"rgba(255,255,255,0.08)\", true) end",
        "  return c",
        "end",
        "",
    ]
    target.write_text("\n".join(lines))
    return len(frames), sum(len(f) for f in frames)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="SOTA shapes JSON")
    parser.add_argument("target", type=Path, help="output Lua scene")
    parser.add_argument("--width", type=int, default=320)
    parser.add_argument("--height", type=int, default=180)
    args = parser.parse_args()
    frames, polygons = convert(args.source, args.target, args.width, args.height)
    print(f"converted {frames} frames / {polygons} polygons -> {args.target}")


if __name__ == "__main__":
    main()
